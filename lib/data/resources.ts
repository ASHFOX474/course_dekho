// ---- lookup helpers -------------------------------------------------

export function getResourcesByTopic(topicId: string): Resource[] {
  return resources.filter((r) => r.topicId === topicId);
}

export function getResourcesByCourse(courseId: string): Resource[] {
  return resources.filter((r) => r.courseId === courseId);
}

export function getResourceById(id: string): Resource | undefined {
  return resources.find((r) => r.id === id);
}

